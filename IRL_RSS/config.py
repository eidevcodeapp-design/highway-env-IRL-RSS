                                        #   追い越しが終わった後は残り70〜90
                                        #   ステップが"平坦なIDLE"になり、
                                        #   本物の車線変更サンプルの絶対数が
                                        #   増えない。一定間隔で再判定する
                                        #   ことで、1エピソードあたり複数回の
                                        #   「追い越すべき」シーンを作り出し、
                                        #   オーバーサンプリング（＝複製）への
                                        #   依存度を下げる）

